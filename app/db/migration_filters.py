"""Alembic autogenerate filters (ADR-0014, NFR-REL-04).

ADK's ``DatabaseSessionService`` creates and owns the ``adk`` schema. Alembic must never
see it: with empty or partial target metadata, autogenerate would otherwise propose
dropping or altering ADK's tables.

``migrations/env.py`` passes :data:`AUTOGENERATE_OPTIONS` to ``context.configure`` and the
unit tests use the same dict, so the tests exercise the real wiring.

Alembic docs: https://alembic.sqlalchemy.org/en/latest/autogenerate.html#controlling-what-to-be-autogenerated
(``include_name`` runs while reflecting names; ``include_object`` runs on built objects).
"""

from typing import Any

# A fixed fact about ADK (not a tunable), so it is a constant here, not in config.yaml.
ADK_SCHEMA = "adk"


def include_name(name: str | None, type_: str, parent_names: dict[str, str | None]) -> bool:
    """Return False for the ``adk`` schema and for anything inside it.

    ``name`` is ``None`` for the connection's default schema, which is kept.
    """
    if type_ == "schema":
        return name != ADK_SCHEMA
    return parent_names.get("schema_name") != ADK_SCHEMA


def include_object(
    obj: Any,
    name: str | None,
    type_: str,
    reflected: bool,
    compare_to: Any,
) -> bool:
    """Return False for any table, column, index or constraint in the ``adk`` schema."""
    return _schema_of(obj) != ADK_SCHEMA


def _schema_of(obj: Any) -> str | None:
    """Schema of a table, or of the table that owns a column, index or constraint."""
    table = getattr(obj, "table", None)
    if table is not None:
        return table.schema  # type: ignore[no-any-return]
    return getattr(obj, "schema", None)


AUTOGENERATE_OPTIONS: dict[str, Any] = {
    "include_schemas": True,
    "include_name": include_name,
    "include_object": include_object,
}
